local Core = RollkeeperCore
local ticket = "RK1|00000000-0000-4000-8000-000000000000|practice|US|Normal|Alliance|25|1000|1|416c64726963|456c617261|53746f726d77696e64|1800000000"
local match = assert(Core.ParseTicket(ticket))
assert(match.players[1] == "Aldric" and match.players[2] == "Elara")
assert(match.zone == "Stormwind" and match.stake == 25)
assert(not Core.ParseTicket(ticket:gsub("practice", "gold")))
assert(not Core.ParseTicket(ticket .. "|unexpected"))
assert(not Core.ParseTicket(ticket:gsub("|25|", "|1001|")))
assert(not Core.ParseTicket(ticket:gsub("416c64726963", "00")))
assert(not Core.ParseTicket(string.rep("a", 1500)))
assert(not Core.ParseTicket(ticket:gsub("416c64726963", "456c617261")))
assert(not Core.Receipt(match, 1800000001))
assert(not Core.Observe(match, "Stranger", 500, 1, 1000))
assert(not Core.Observe(match, "Elara", 500, 1, 1000))
assert(not Core.Observe(match, "Aldric", 500, 1, 500))
assert(not Core.Observe(match, "Aldric", 0, 1, 1000))
assert(Core.Observe(match, "Aldric", 500, 1, 1000))
assert(match.turn == 2 and match.maximum == 500)
assert(not Core.Observe(match, "Aldric", 500, 1, 1000))
assert(Core.Observe(match, "Elara", 1, 1, 500))
assert(match.loser == 2 and #match.rolls == 2)
assert(not Core.Observe(match, "Aldric", 1, 1, 1))
assert(Core.Receipt(match, 1800000001) == "RKR1|00000000-0000-4000-8000-000000000000|practice|player2|1800000001")
local parser = assert(Core.RollParser("%s rolls %d (%d-%d)"))
local name, value, low, high = parser("Aldric rolls 123 (1-1000)")
assert(name == "Aldric" and value == 123 and low == 1 and high == 1000)
local spoofName = parser("[Aldric]: Aldric rolls 123 (1-1000)")
assert(spoofName ~= "Aldric") -- Only exact participant names are accepted by Observe.
local localized = assert(Core.RollParser("%1$s obtient %2$d (%3$d-%4$d)"))
local n, v, l, h = localized("Élara Moonwell obtient 9 (1-100)")
assert(n == "Élara Moonwell" and v == 9 and l == 1 and h == 100)
assert(not Core.RollParser("unsupported"))
